#!/usr/bin/env node
// Bundle the reference WebGPU port of OpenDLSS-NR into the package, for the `three-dlss-nr/reference-backend` entry.
//
// OpenDLSS-NR by maan (https://github.com/maanHimself/OpenDLSS-NR) is MIT licensed, Copyright (c) 2026 maan. Its
// browser port (ports/browser-webgpu) is the reference this package ports to TSL; the "reference-wgsl" backend runs
// that port's own JavaScript and WGSL unchanged on three.js' GPUDevice. The published package must not depend on the
// git submodule (reference/OpenDLSS-NR) existing, so this script copies what the backend needs into
// packages/three-dlss-nr/vendor/opendlss-nr/ (git-ignored, published via package.json "files"):
//
//   * every ES module reachable from src/network.js, byte for byte, behind a header naming the upstream file,
//     the commit and the license (`// ...` lines only; the module text after the header is untouched);
//   * shaders.js: the WGSL files the network and its frame kernels compile, inlined as string constants
//     (the upstream loads them with fetch(), which a bundled package cannot rely on);
//   * index.js / index.d.ts: the re-exports the backend imports, typed loosely;
//   * LICENSE (upstream MIT text) and SOURCE.json (commit, file list, SHA-256 of every source file).
//
// Usage: node packages/three-dlss-nr/scripts/bundle-reference.mjs [--check]
//   --check  exit 1 if the vendored copy is missing or differs from what the submodule would produce.
// Without the submodule (e.g. building from a published tarball) an existing vendor directory is kept as is.

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The upstream commit this package is pinned to (the submodule must be checked out at it). */
export const UPSTREAM_COMMIT = '9d08f4184bbcb9d858e2fb7a7834ec0837a9d2f1';
export const UPSTREAM_URL = 'https://github.com/maanHimself/OpenDLSS-NR';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(packageRoot, '../..');
export const submoduleRoot = join(repoRoot, 'reference/OpenDLSS-NR');
export const portRoot = join(submoduleRoot, 'ports/browser-webgpu');
export const vendorRoot = join(packageRoot, 'vendor/opendlss-nr');

/** The WGSL files the backend compiles: the network's four, numerics, and the demo's frame kernels. */
export const WGSL_FILES = ['numerics.wgsl', 'gemm_f16.wgsl', 'vit.wgsl', 'ops.wgsl', 'preprocess.wgsl', 'frame.wgsl'];

/** Names index.js re-exports (module path relative to src/, names). */
const EXPORTS = [
  ['network.js', ['Network']],
  ['gpu.js', ['readBack', 'align']],
  ['passes.js', ['Kernels', 'Tensors', 'Recorder', 'BINDING_COUNT', 'PARAMS_STRIDE']],
  ['model.js', ['Model']],
  ['graph.js', ['Graph']],
  ['geometry.js', ['geometryFromValid']],
  ['matmul/index.js', ['Matmul']],
  ['window/index.js', ['WindowAttention', 'requireWorkgroupStorage', 'WINDOW_WORKGROUP_STORAGE']],
];

const sha256 = (text) => createHash('sha256').update(text).digest('hex');

/** The header prepended to a vendored file (`//` lines). */
export function vendorHeader(upstreamPath) {
  return [
    `// Vendored verbatim from OpenDLSS-NR by maan (${UPSTREAM_URL}), file ${upstreamPath}`,
    `// at commit ${UPSTREAM_COMMIT}. MIT License, Copyright (c) 2026 maan (see LICENSE beside this file).`,
    '// Generated by packages/three-dlss-nr/scripts/bundle-reference.mjs for three-dlss-nr/reference-backend;',
    '// do not edit. Everything below this header is the upstream file, byte for byte.',
    '',
  ].join('\n');
}

/** Every module reachable from src/network.js through relative static imports, as paths relative to src/. */
export function reachableModules(srcRoot) {
  const seen = new Set();
  const visit = (path) => {
    if (seen.has(path)) return;
    seen.add(path);
    const text = readFileSync(join(srcRoot, path), 'utf8');
    for (const match of text.matchAll(/^\s*(?:import|export)\s[^;]*?from\s+'(\.[^']+)'/gms)) {
      visit(posix.normalize(posix.join(posix.dirname(path), match[1])));
    }
  };
  visit('network.js');
  return [...seen].toSorted();
}

/**
 * The environment for git commands run on the submodule. Git hooks (e.g. pre-commit) export GIT_DIR, GIT_INDEX_FILE
 * and friends for the superproject, which would override `-C <submodule>`.
 */
export function gitEnv() {
  return Object.fromEntries(Object.entries(process.env).filter(([name]) => !name.startsWith('GIT_')));
}

function submoduleCommit() {
  try {
    return execFileSync('git', ['-C', submoduleRoot, 'rev-parse', 'HEAD'], { encoding: 'utf8', env: gitEnv() }).trim();
  } catch {
    return null;
  }
}

const INDEX_DTS = `// Types for the vendored OpenDLSS-NR reference WebGPU port (plain JavaScript, MIT, by maan).
// Generated by packages/three-dlss-nr/scripts/bundle-reference.mjs; do not edit. The upstream modules are untyped;
// three-dlss-nr's ReferenceWgslBackend narrows what it uses.
/* eslint-disable */
export declare const Network: any;
export declare function readBack(device: GPUDevice, buffer: GPUBuffer, byteLength: number): Promise<ArrayBuffer>;
export declare function align(value: number, to: number): number;
export declare const Kernels: any;
export declare const Tensors: any;
export declare const Recorder: any;
export declare const BINDING_COUNT: number;
export declare const PARAMS_STRIDE: number;
export declare const Model: any;
export declare const Graph: any;
export declare function geometryFromValid(validWidth: number, validHeight: number): any;
export declare const Matmul: any;
export declare const WindowAttention: any;
export declare function requireWorkgroupStorage(device: GPUDevice): void;
export declare const WINDOW_WORKGROUP_STORAGE: number;
/** The WGSL sources, by file name (shaders/<name> upstream). */
export declare const SHADERS: Readonly<Record<string, string>>;
/** Upstream provenance: repository, commit, and SHA-256 of every vendored source file. */
export declare const SOURCE: {
  readonly repository: string;
  readonly commit: string;
  readonly files: Readonly<Record<string, string>>;
};
`;

/** The vendored files, as a Map of path (relative to the vendor root) -> text. */
export function vendoredFiles() {
  const srcRoot = join(portRoot, 'src');
  const files = new Map();
  const provenance = {};
  for (const path of reachableModules(srcRoot)) {
    const text = readFileSync(join(srcRoot, path), 'utf8');
    const upstreamPath = `ports/browser-webgpu/src/${path}`;
    provenance[upstreamPath] = sha256(text);
    files.set(`src/${path}`, vendorHeader(upstreamPath) + text);
  }
  const shaders = {};
  for (const name of WGSL_FILES) {
    const text = readFileSync(join(portRoot, 'shaders', name), 'utf8');
    provenance[`ports/browser-webgpu/shaders/${name}`] = sha256(text);
    shaders[name] = text;
  }
  const source = { repository: UPSTREAM_URL, commit: UPSTREAM_COMMIT, files: provenance };
  files.set(
    'shaders.js',
    vendorHeader(`ports/browser-webgpu/shaders/{${WGSL_FILES.join(',')}}`).replace(
      'Everything below this header is the upstream file, byte for byte.',
      'Each string below is the upstream WGSL file, byte for byte.',
    ) +
      `export const SHADERS = Object.freeze(${JSON.stringify(shaders, null, 2)});\n` +
      `export const SOURCE = Object.freeze(${JSON.stringify(source, null, 2)});\n`,
  );
  const reexports = EXPORTS.map(([path, names]) => `export { ${names.join(', ')} } from './src/${path}';`);
  files.set(
    'index.js',
    `// The parts of the vendored OpenDLSS-NR reference WebGPU port (MIT, by maan) that three-dlss-nr's\n` +
      `// ReferenceWgslBackend drives. Generated by packages/three-dlss-nr/scripts/bundle-reference.mjs; do not edit.\n` +
      `${reexports.join('\n')}\nexport { SHADERS, SOURCE } from './shaders.js';\n`,
  );
  files.set('index.d.ts', INDEX_DTS);
  files.set('LICENSE', readFileSync(join(submoduleRoot, 'LICENSE'), 'utf8'));
  files.set('SOURCE.json', `${JSON.stringify(source, null, 2)}\n`);
  return files;
}

function listExisting(root) {
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else found.push(relative(root, path).split('\\').join('/'));
    }
  };
  if (existsSync(root)) walk(root);
  return found.toSorted();
}

function main() {
  const check = process.argv.includes('--check');
  if (!existsSync(join(portRoot, 'src/network.js'))) {
    if (existsSync(join(vendorRoot, 'index.js')) && !check) {
      console.log('bundle-reference: no submodule; keeping the existing vendor/opendlss-nr');
      return;
    }
    console.error(
      'bundle-reference: reference/OpenDLSS-NR is missing; run `git submodule update --init` (the reference ' +
        'backend bundles it at build time)',
    );
    process.exit(1);
  }
  const commit = submoduleCommit();
  if (commit && commit !== UPSTREAM_COMMIT) {
    console.error(`bundle-reference: the submodule is at ${commit}, expected ${UPSTREAM_COMMIT}`);
    process.exit(1);
  }
  const files = vendoredFiles();
  const existing = listExisting(vendorRoot);
  const stale = existing.filter((path) => !files.has(path));
  const changed = [...files].filter(([path, text]) => {
    const target = join(vendorRoot, path);
    return !existsSync(target) || readFileSync(target, 'utf8') !== text;
  });
  if (check) {
    if (changed.length || stale.length) {
      console.error(
        `bundle-reference: vendor/opendlss-nr is out of date (${changed.length} changed, ${stale.length} stale); ` +
          'run node packages/three-dlss-nr/scripts/bundle-reference.mjs',
      );
      process.exit(1);
    }
    console.log(`bundle-reference: vendor/opendlss-nr is up to date (${files.size} files)`);
    return;
  }
  for (const path of stale) rmSync(join(vendorRoot, path));
  for (const [path, text] of changed) {
    const target = join(vendorRoot, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
  }
  if (changed.length || stale.length) {
    console.log(
      `bundle-reference: wrote ${changed.length} of ${files.size} files to vendor/opendlss-nr ` +
        `(OpenDLSS-NR ${UPSTREAM_COMMIT.slice(0, 7)})`,
    );
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
